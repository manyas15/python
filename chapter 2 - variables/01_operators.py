# variables
# a= 1 -> here a is a variable and 1 is the value of the variable

# datatypes
# int, float, str, bool, none, list, tuple, set, dict

# operators
# arithmetic operators -> +, -, *, /, %, **, //
# comparison operators -> ==, !=, <, >, <=, >=    -> always return boolean value true or false
# logical operators -> and, or, not
# assignment operators -> =, +=, -=, *=, /=, %=, **=, //=

# arithmetic operators
a = 7
b = 4
c = a + b
print(c)

# assignment operators
a = 4 - 2  # assign 4 - 2 to a
print(a)
b = 6
b += 3
print(b)  # increment the value of b by 3 and then assign it to b

# comparison operators
d = 5 > 4
print(d)  # True

# logical operators
e = True and False
print(e)  # False
f = True or False
print(f)  # True

g = not True  # works on single boolean value 
print(g)  # False





