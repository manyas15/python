# \n is a escape sequence that represents a new line character. It is used to insert a line break in a string. 
a = "Manya is a good girl\nshe is 22 years old"
print(a)

# \t is a escape sequence that represents a tab character. It is used to insert a tab space in a string.
b = "Manya is a good girl\tShe is 22 years old"
print(b)

# \\ is a escape sequence that represents a backslash character. It is used to insert a backslash in a string.
c = "Manya is a good girl\\She is 22 years old"
print(c)

# \' is a escape sequence that represents a single quote character. It is used to insert a single quote in a string.
d = 'Manya is a good girl\'She is 22 years old'
print(d)

# \" is a escape sequence that represents a double quote character. It is used to insert a double quote in a string.
e = "Manya is a good girl\"She is 22 years old"
print(e)
